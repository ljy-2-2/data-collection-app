#!/usr/bin/env python3
"""Remove optional vendor uploader credentials from the distribution copy only."""

from pathlib import Path
import sys

import yaml

SECRET_KEYS = {
    "api_key",
    "s3_access_key_id",
    "s3_secret_access_key",
    "access_token",
    "auth_token",
    "password",
    "secret_key",
    "client_secret",
}


def clear_secrets(value):
    if isinstance(value, dict):
        return {
            key: "" if str(key).lower() in SECRET_KEYS else clear_secrets(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [clear_secrets(item) for item in value]
    return value


def main():
    app = Path(sys.argv[1])
    # This file is generated by the hardware selector and may contain local keys.
    config = (
        app / "umi_collection/vendor/galaxis/galaxis_bringup/config/galaxis_config.yaml"
    )
    if config.is_file():
        payload = clear_secrets(yaml.safe_load(config.read_text()))
        config.write_text(yaml.safe_dump(payload, allow_unicode=True, sort_keys=False))


if __name__ == "__main__":
    main()
